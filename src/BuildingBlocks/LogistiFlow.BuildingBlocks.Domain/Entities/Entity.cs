namespace LogistiFlow.BuildingBlocks.Domain.Entities;

/// <summary>
/// Base type for aggregate roots that follow the dual-identifier convention:
/// <see cref="Id"/> is the internal surrogate key and is never exposed outside the process;
/// <see cref="PublicId"/> is the stable identifier used in routes, APIs and cross-module contracts.
/// </summary>
public abstract class Entity
{
    public long Id { get; protected set; }

    public Guid PublicId { get; protected set; }

    public bool IsActive { get; protected set; } = true;

    public DateTimeOffset CreatedAt { get; protected set; }

    public DateTimeOffset UpdatedAt { get; protected set; }

    protected void Initialize(DateTimeOffset now)
    {
        PublicId = Guid.CreateVersion7(now);
        IsActive = true;
        CreatedAt = now;
        UpdatedAt = now;
    }

    protected void Touch(DateTimeOffset now) => UpdatedAt = now;

    /// <summary>Rehydrates the identity and audit columns of an entity loaded from storage.</summary>
    protected void Restore(long id, Guid publicId, bool isActive, DateTimeOffset createdAt, DateTimeOffset updatedAt)
    {
        Id = id;
        PublicId = publicId;
        IsActive = isActive;
        CreatedAt = createdAt;
        UpdatedAt = updatedAt;
    }

    /// <summary>Sets the surrogate key generated by the database on insert.</summary>
    public void AssignId(long id)
    {
        if (Id != 0)
        {
            throw new InvalidOperationException("The entity already has an identifier.");
        }

        Id = id;
    }
}
